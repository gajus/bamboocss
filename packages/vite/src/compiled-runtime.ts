import type { Plugin } from 'vite'
import compiledRuntime from './generated/compiled.mjs.json' with { type: 'json' }

/**
 * The module compiled code imports the helpers it calls from: `cvaMap` for a recipe lookup, and
 * `splitProps` for a lowered `recipe.splitVariantProps`.
 *
 * The plugin serves it from the `@bamboocss/shared` it was built with (`src/compiled.ts`, bundled and
 * copied here by that package's postbuild), so a compiled call and the helper it reaches are one
 * release's, always. A `styled-system` is not: the plugin writes the project's own, but compiled code
 * can reach others, such as a workspace design system's, generated by whatever release last ran
 * there, and the tables `cvaMap` reads have changed format between releases.
 */
export const COMPILED_RUNTIME_ID = 'virtual:bamboo/compiled'

const RESOLVED_ID = `\0${COMPILED_RUNTIME_ID}`

/** Serves `virtual:bamboo/compiled`. @see COMPILED_RUNTIME_ID */
export const bamboocssCompiledRuntime = (): Plugin => ({
  name: 'bamboocss:compiled-runtime',

  resolveId(id) {
    return id === COMPILED_RUNTIME_ID || id === RESOLVED_ID ? RESOLVED_ID : null
  },

  load(id) {
    // A dev server can re-request a module with a timestamp query once it has been invalidated.
    return id.split('?')[0] === RESOLVED_ID ? compiledRuntime.content : null
  },
})
