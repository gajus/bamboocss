import type { Plugin } from 'vite'
import compiledRuntime from './generated/compiled.mjs.json' with { type: 'json' }

/**
 * The module compiled code imports what it calls at runtime from: `cvaMap` for a recipe lookup,
 * `splitProps` for a lowered `recipe.splitVariantProps`, and `cx` for a join of the classes it
 * compiled with ones it cannot see.
 *
 * The plugin serves it itself, so a compiled call and what it reaches are one release's, always:
 * the first two from the `@bamboocss/shared` it was built with (`src/compiled.ts`, bundled and copied
 * here by that package's postbuild), and `cx` as its generator writes it for this project's
 * `prefix`. A `styled-system` is neither. The plugin writes the project's own, but compiled code can
 * reach others, such as a workspace design system's, generated by whatever release last ran there
 * and for that package's config: the tables `cvaMap` reads have changed format between releases,
 * and `cx` reads as atoms only classes carrying the prefix it was generated for.
 */
export const COMPILED_RUNTIME_ID = 'virtual:bamboo/compiled'

const RESOLVED_ID = `\0${COMPILED_RUNTIME_ID}`

/** The module's text, given `cx` as `generateCxRuntime` writes it for the project's prefix. */
export const compiledRuntimeSource = (cx: string) => `${compiledRuntime.content}\n${cx}\n\nexport { cx };\n`

/**
 * Serves `virtual:bamboo/compiled`. @see COMPILED_RUNTIME_ID
 *
 * `cx` is asked for on every load rather than once, since it is the current config's: a dev server
 * restarts when the config changes, and loads the module again.
 */
export const bamboocssCompiledRuntime = (cx: () => Promise<string>): Plugin => ({
  name: 'bamboocss:compiled-runtime',

  resolveId(id) {
    return id === COMPILED_RUNTIME_ID || id === RESOLVED_ID ? RESOLVED_ID : null
  },

  async load(id) {
    // A dev server can re-request a module with a timestamp query once it has been invalidated.
    if (id.split('?')[0] !== RESOLVED_ID) return null
    return compiledRuntimeSource(await cx())
  },
})
